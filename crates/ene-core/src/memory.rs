/// Explainable score breakdown for a recalled memory.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct MemoryScoreBreakdown {
    /// Raw vector cosine similarity.
    pub vector_similarity: f32,
    /// Lexical overlap score.
    pub lexical_score: f32,
    /// Recency decay score.
    pub recency_score: f32,
    /// Memory salience value.
    pub salience: f32,
    /// Memory confidence value used in the weighted score.
    pub confidence: f32,
    /// Affect match score.
    pub emotional_match: f32,
    /// Normalized relationship impact score.
    pub relationship: f32,
    /// Access-frequency boost.
    pub access_boost: f32,
    /// Combined query-relevance signal in `[0, 1]` — the weighted blend of
    /// vector similarity and lexical overlap that forms the score base.
    pub relevance: f32,
    /// Multiplicative quality factor `>= 1.0` built from the salience,
    /// confidence, recency, affect, relationship, and access signals.
    pub quality_factor: f32,
    /// Penalty for disputed status.
    pub contradiction_penalty: f32,
    /// Penalty for faded or expired memories.
    pub stale_penalty: f32,
    /// Boost for active commitment candidates.
    pub commitment_boost: f32,
    /// Self-reflection adjustment multiplier applied after scoring.
    ///
    /// `1.0` means no reflection adjustment. A value `> 1.0` boosts memories
    /// matching successful strategies; `< 1.0` penalizes memories matching
    /// strategies to avoid. Recorded so the explainable breakdown stays
    /// consistent: `total` is the pre-reflection score scaled by this factor,
    /// rather than a silent overwrite of `total`.
    pub reflection_multiplier: f32,
    /// Final hybrid total score.
    pub total: f32,
}

impl Default for MemoryScoreBreakdown {
    fn default() -> Self {
        Self {
            vector_similarity: 0.0,
            lexical_score: 0.0,
            recency_score: 0.0,
            salience: 0.0,
            confidence: 0.0,
            emotional_match: 0.0,
            relationship: 0.0,
            access_boost: 0.0,
            relevance: 0.0,
            quality_factor: 1.0,
            contradiction_penalty: 0.0,
            stale_penalty: 0.0,
            commitment_boost: 0.0,
            reflection_multiplier: 1.0,
            total: 0.0,
        }
    }
}

/// A typed memory with hybrid score breakdown and recall sources.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ScoredMemory {
    /// The recalled memory item.
    pub item: MemoryItem,
    /// Explainable score components.
    pub breakdown: MemoryScoreBreakdown,
    /// Sources that contributed this candidate.
    pub sources: Vec<MemoryCandidateSource>,
}

/// A candidate gathered from one or more recall sources, before scoring.
///
/// Produced by [`MemoryPort::search`](crate::MemoryPort::search) and consumed
/// by the `ene-rag` scoring layer. Lives in `ene-core` so both the store
/// (gatherer) and the RAG crate (scorer) can name it without a cycle.
///
/// Carries `Serialize`/`Deserialize` so it can cross a process boundary in the
/// future (e.g. an out-of-process store). Note that each candidate embeds a full
/// [`MemoryItem`] — including its `content` string — so a large candidate set can
/// produce a sizeable serialized payload; any future IPC path should stay
/// size-aware (cap candidate counts, or send identifiers instead of full items).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct GatheredCandidate {
    /// The recalled memory item.
    pub item: MemoryItem,
    /// Best vector cosine similarity across recall sources (0.0 when absent).
    pub vector_similarity: f32,
    /// Sources that contributed this candidate.
    pub sources: Vec<MemoryCandidateSource>,
}

