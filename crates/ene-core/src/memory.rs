/// Recall source that surfaced a memory candidate.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
#[non_exhaustive]
pub enum MemoryCandidateSource {
    /// Vector embedding similarity search.
    Vector,
    /// Lexical token overlap with query text.
    Lexical,
    /// Recent / active memory listing.
    Recent,
    /// Active companion commitment ledger.
    Commitment,
    /// Unconfirmed candidate awaiting user approval.
    ///
    /// Candidates the arbiter deferred with `AskConfirmationLater` live in the
    /// pending queue rather than the typed-memory table. They still compete in
    /// hybrid recall so the character can ask about them when the topic comes
    /// up; this source marks them as unconfirmed in the prompt.
    Pending,
}

/// Weights for hybrid memory search scoring components.
///
/// The hybrid score is *relevance-driven*: `vector` and `lexical` form the
/// relevance base that decides whether a memory is a candidate at all, while
/// `recency`, `salience`, `confidence`, `emotional_match`, `relationship`, and
/// `access_boost` form a multiplicative quality factor that only reorders
/// memories *within* the relevant set. Quality can therefore never lift an
/// irrelevant memory above a relevant one.
///
/// Product defaults are supplied by `mind.memory.hybrid_weights`
/// (`ene_mind::MindMemoryConfig`); the store only applies caller-provided
/// weights when scoring.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize, schemars::JsonSchema)]
#[serde(rename_all = "snake_case", default)]
#[schemars(crate = "schemars")]
pub struct HybridSearchWeights {
    /// Relevance weight for vector cosine similarity.
    pub vector: f32,
    /// Relevance weight for lexical token overlap.
    pub lexical: f32,
    /// Quality weight for recency decay score.
    pub recency: f32,
    /// Quality weight for memory salience.
    pub salience: f32,
    /// Quality weight for memory confidence.
    pub confidence: f32,
    /// Quality weight for emotional/affect match.
    pub emotional_match: f32,
    /// Quality weight for relationship impact.
    pub relationship: f32,
    /// Quality weight for prior access boost.
    pub access_boost: f32,
}

impl Default for HybridSearchWeights {
    fn default() -> Self {
        Self {
            vector: 0.40,
            lexical: 0.15,
            recency: 0.10,
            salience: 0.15,
            confidence: 0.05,
            emotional_match: 0.05,
            relationship: 0.05,
            access_boost: 0.05,
        }
    }
}

/// A time range filter for memory queries.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TimeRange {
    /// Start of the time range (inclusive).
    pub start: Option<DateTime<Utc>>,
    /// End of the time range (inclusive).
    pub end: Option<DateTime<Utc>>,
}

/// Typed-memory search query.
///
/// Callers (mind) pre-compute `embedding` when vector search is desired.
/// `None` skips the vector gather path and scores lexical/recency/commitment
/// candidates only. The store never calls an embedder.
#[derive(Debug, Clone)]
pub struct Query<'a> {
    /// Natural-language query for lexical scoring.
    pub query_text: &'a str,
    /// Optional query embedding for vector similarity (`None` = lexical/recency only).
    pub embedding: Option<&'a [f32]>,
    /// Character scope.
    pub character_id: &'a str,
    /// Optional user scope filter.
    pub user_id: Option<&'a str>,
    /// Embedding model name for vector index lookup (ignored when `embedding` is `None`).
    pub model_name: &'a str,
    /// Maximum results to return.
    pub limit: usize,
    /// Minimum vector similarity for vector-sourced candidates.
    pub similarity_threshold: f32,
    /// Upper bound on candidates gathered before scoring.
    pub candidate_pool_size: usize,
    /// Optional query affect for emotional match scoring.
    pub query_affect: Option<AffectAnnotation>,
    /// Component weights for the hybrid formula.
    pub weights: HybridSearchWeights,
    /// Half-life in days for recency decay.
    pub decay_half_life_days: f64,
    /// Half-life in days for the access-boost recency decay.
    ///
    /// Independent of [`Self::decay_half_life_days`]: access history fades on
    /// this shorter timescale so old accesses stop boosting recall score well
    /// before the memory itself would fade. Defaults to
    /// `ene_rag::ACCESS_BOOST_HALF_LIFE_DAYS` (14.0) via mind config.
    pub access_boost_half_life_days: f64,
    /// Reference time for recency and expiry checks.
    pub now: DateTime<Utc>,
    /// Minimum hybrid total score required to return a result.
    pub min_score: f32,
    /// Boost applied when a candidate is surfaced via an active commitment.
    pub commitment_boost: f32,
    /// Filter by time range (for world state queries like "what was I doing yesterday?").
    pub time_range: Option<TimeRange>,
    /// Limit on pure-recent fallback candidates.
    pub recent_fallback_limit: usize,
    /// Memory kinds excluded from every gather path.
    ///
    /// Candidates of an excluded kind are dropped before scoring, so they
    /// never compete with normal memories in recall. The cognitive recall
    /// path uses this to keep [`MemoryKind::Reflection`] memories out of
    /// regular recall: reflections are a scoring signal (applied separately
    /// via the self-reflection pipeline), not context to inject into the LLM.
    /// An empty list excludes nothing.
    pub exclude_kinds: Vec<MemoryKind>,
}

