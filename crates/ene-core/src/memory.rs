//! Typed memory domain model.

use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};

/// The kind of a typed memory item.
///
/// Each memory has exactly one kind, which drives retrieval strategy
/// and lifecycle behaviour.
///
/// ## Per-kind policy table
///
/// Every aspect below is defined in code by an exhaustive `match` on this enum
/// (see [`MemoryKind::is_llm_extractable`], [`MemoryKind::is_contradiction_kind`],
/// [`MemoryKind::contradiction_key_match`], [`MemoryKind::has_diversification_base_slot`],
/// [`MemoryKind::is_recall_eligible`], [`MemoryKind::forgetting_policy`]), so a new
/// variant cannot be added without deciding each aspect — there are no
/// `matches!` / `_ =>` fallbacks that hide omissions. Consumers in `ene-mind`
/// (arbiter, diversification, recall, commitment ledger) route through these
/// methods rather than re-deriving the policy locally, keeping the definition
/// in this one place.
///
/// | Kind | LLM-extractable | Contradiction-checked | Contradiction key | Diversification base slot | Normal recall | Forgetting |
/// |---|---|---|---|---|---|---|
/// | Episodic | ✓ | — | — | ✓ | ✓ | standard |
/// | Semantic | ✓ | ✓ | vector (title embedding) | ✓ | ✓ | standard |
/// | `UserProfile` | ✓ | ✓ | vector (title embedding) | ✓ | ✓ | standard |
/// | Relationship | ✓ | ✓ | vector (title embedding) | — | ✓ | standard |
/// | Affective | ✓ | — | — | — | ✓ | standard |
/// | Commitment | ✓ | ✓ | vector (title embedding) | ✓ | ✓ | standard |
/// | Preference | ✓ | ✓ | vector (title embedding) | — | ✓ | standard |
/// | Procedure | ✓ | — | — | — | ✓ | standard |
/// | `WorldState` | — (reserved) | — | — | — | ✓ | standard |
/// | Reflection | ✓ | — | — | — | ✗ | standard |
///
/// **LLM-extractable** refers to the extractor's parse table
/// (`ene-mind/src/memory_writer/llm.rs`): the kinds the model may legitimately
/// produce. [`MemoryKind::WorldState`] is deliberately absent (see its variant
/// doc).
///
/// **Contradiction key** is the method used to decide two same-kind memories
/// talk about the same subject: *vector (title embedding)* compares
/// title embeddings by cosine similarity with an exact normalized-title
/// fallback when no embedder is available.
///
/// **Forgetting**: all kinds currently share the single global half-life
/// (`mind.memory.default_forgetting_half_life_days`); there is no
/// per-kind differentiation yet. Per-item `pinned` memories are exempt.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
#[non_exhaustive]
pub enum MemoryKind {
    /// Specific events or conversations (what happened when).
    Episodic,
    /// Facts and general knowledge (what is true).
    Semantic,
    /// Information about the user's identity, background, and traits.
    UserProfile,
    /// Information about the relationship between the user and the companion.
    Relationship,
    /// Memories with strong emotional salience.
    Affective,
    /// Promises, tasks, and obligations the companion has made.
    Commitment,
    /// User likes, dislikes, and preferences.
    Preference,
    /// How-to knowledge and procedural instructions.
    Procedure,
    /// Observation of the user's environment/activity at a point in time.
    ///
    /// **Defined but unreachable today**: reserved for structured time-series
    /// world state and not yet generated by any producer. The LLM
    /// extractor deliberately rejects it (see [`MemoryKind::is_llm_extractable`])
    /// and no deterministic or tool producer emits it, so rows of this kind can
    /// only appear via direct store writes or future work.
    WorldState,
    /// Self-reflections by the companion about past interactions.
    Reflection,
}

/// How two memories of the same kind are keyed to the same subject for
/// contradiction checking.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ContradictionKeyMatch {
    /// Titles are compared by embedding cosine similarity, with an exact
    /// normalized-title fallback when no embedder is available.
    VectorTitle,
    /// This kind is not contradiction-checked (the key is never consulted).
    NotChecked,
}

/// Natural-forgetting treatment for a memory kind.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ForgettingPolicy {
    /// Standard decay using the global `default_forgetting_half_life_days`.
    ///
    /// Today every kind is `Standard` — no per-kind half-life exists yet. This
    /// variant is the extension point where a per-kind half-life would be
    /// introduced (as a new variant carrying the multiplier or override).
    Standard,
}

impl MemoryKind {
    /// Returns the `snake_case` string representation for storage/DB use.
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Episodic => "episodic",
            Self::Semantic => "semantic",
            Self::UserProfile => "user_profile",
            Self::Relationship => "relationship",
            Self::Affective => "affective",
            Self::Commitment => "commitment",
            Self::Preference => "preference",
            Self::Procedure => "procedure",
            Self::WorldState => "world_state",
            Self::Reflection => "reflection",
        }
    }

    /// Parse from a `snake_case` string, logging a warning on unrecognized values.
    pub fn from_db_str(s: &str) -> Self {
        match s {
            "episodic" => Self::Episodic,
            "semantic" => Self::Semantic,
            "user_profile" => Self::UserProfile,
            "relationship" => Self::Relationship,
            "affective" => Self::Affective,
            "commitment" => Self::Commitment,
            "preference" => Self::Preference,
            "procedure" => Self::Procedure,
            "world_state" => Self::WorldState,
            "reflection" => Self::Reflection,
            other => {
                tracing::error!(
                    other,
                    "unrecognized MemoryKind in DB, falling back to Semantic"
                );
                Self::Semantic
            }
        }
    }

    /// All defined variants in declaration order.
    ///
    /// Used by policy tables and by callers that must iterate every kind
    /// (diversification quotas, the LLM extractor schema, exhaustive tests).
    /// Keep in sync with the variant list when adding a kind.
    pub const ALL: [Self; 10] = [
        Self::Episodic,
        Self::Semantic,
        Self::UserProfile,
        Self::Relationship,
        Self::Affective,
        Self::Commitment,
        Self::Preference,
        Self::Procedure,
        Self::WorldState,
        Self::Reflection,
    ];

    /// Whether the LLM extractor may produce this kind (`memory_writer/llm.rs`
    /// parse table).
    ///
    /// [`Self::WorldState`] is deliberately not extractable: it is reserved for
    /// structured time-series world state and no producer exists yet, so
    /// an LLM candidate labelled `WorldState` hits the explicit rejection arm
    /// and falls back to Semantic with a warning rather than being silently
    /// produced.
    pub const fn is_llm_extractable(self) -> bool {
        match self {
            Self::Episodic
            | Self::Semantic
            | Self::UserProfile
            | Self::Relationship
            | Self::Affective
            | Self::Commitment
            | Self::Preference
            | Self::Procedure
            | Self::Reflection => true,
            Self::WorldState => false,
        }
    }

    /// Whether an incoming candidate of this kind is checked for contradictions
    /// against existing same-kind memories (`memory_writer/arbiter.rs`).
    ///
    /// The identity-like kinds (Semantic, `UserProfile`, Preference,
    /// Relationship) plus Commitment: a rephrased or updated commitment must
    /// supersede the prior record rather than accumulate. In the normal
    /// write path commitment candidates bypass the typed arbiter — the
    /// commitment ledger (`ene-mind/src/commitments/mod.rs`) enforces the same
    /// title-keyed update/cancel semantics as the source of truth; this entry
    /// is the typed-memory path's defense in depth.
    pub const fn is_contradiction_kind(self) -> bool {
        match self {
            Self::Semantic
            | Self::UserProfile
            | Self::Preference
            | Self::Relationship
            | Self::Commitment => true,
            Self::Episodic
            | Self::Affective
            | Self::Procedure
            | Self::WorldState
            | Self::Reflection => false,
        }
    }

    /// How the contradiction check keys two same-kind memories to the same
    /// subject. Only meaningful when [`Self::is_contradiction_kind`] is
    /// true.
    pub const fn contradiction_key_match(self) -> ContradictionKeyMatch {
        match self {
            Self::Semantic
            | Self::UserProfile
            | Self::Preference
            | Self::Relationship
            | Self::Commitment => ContradictionKeyMatch::VectorTitle,
            Self::Episodic
            | Self::Affective
            | Self::Procedure
            | Self::WorldState
            | Self::Reflection => ContradictionKeyMatch::NotChecked,
        }
    }

    /// Whether this kind reserves a guaranteed base slot in recall
    /// diversification (`ene-mind/src/recall/diversify.rs`). Kinds without a
    /// base slot still surface dynamically when they are relevant enough.
    pub const fn has_diversification_base_slot(self) -> bool {
        match self {
            Self::Semantic | Self::Episodic | Self::UserProfile | Self::Commitment => true,
            Self::Relationship
            | Self::Affective
            | Self::Preference
            | Self::Procedure
            | Self::WorldState
            | Self::Reflection => false,
        }
    }

    /// Whether this kind is eligible for normal (cognitive) recall.
    ///
    /// [`Self::Reflection`] is excluded: reflections are a scoring signal
    /// applied separately by the self-reflection pipeline, never context
    /// injected into the LLM.
    pub const fn is_recall_eligible(self) -> bool {
        match self {
            Self::Episodic
            | Self::Semantic
            | Self::UserProfile
            | Self::Relationship
            | Self::Affective
            | Self::Commitment
            | Self::Preference
            | Self::Procedure
            | Self::WorldState => true,
            Self::Reflection => false,
        }
    }

    /// Natural-forgetting treatment for this kind.
    ///
    /// Today every kind is [`ForgettingPolicy::Standard`]: the sweep applies a
    /// single global half-life (`mind.memory.default_forgetting_half_life_days`)
    /// to all kinds, with per-item `pinned` memories exempt. This exhaustive
    /// match is the extension point where a per-kind half-life would be
    /// introduced.
    pub const fn forgetting_policy(self) -> ForgettingPolicy {
        match self {
            Self::Episodic
            | Self::Semantic
            | Self::UserProfile
            | Self::Relationship
            | Self::Affective
            | Self::Commitment
            | Self::Preference
            | Self::Procedure
            | Self::WorldState
            | Self::Reflection => ForgettingPolicy::Standard,
        }
    }
}

/// The lifecycle status of a memory.
